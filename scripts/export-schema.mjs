/**
 * Gera supabase/schema.sql: o esquema final do banco (tabelas, funções, gatilhos,
 * RLS, permissões e agendamentos), lido do catálogo de um Postgres embutido (PGlite)
 * depois de aplicar todas as migrações em ordem. Só estrutura, nenhum dado.
 *   npm run db:schema
 * A fonte de verdade continua sendo supabase/migrations/; este arquivo é a referência
 * legível do resultado.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { runnerImport } from 'vite';

const { createDevDatabase } = (await runnerImport('./scripts/lib/pglite-db.ts', { configFile: false, logLevel: 'error' })).module;
const db = await createDevDatabase();
const rows = async (sql) => (await db.query(sql)).rows;
const out = [];
const section = (title) => out.push('', `-- ${'='.repeat(76)}`, `-- ${title}`, `-- ${'='.repeat(76)}`, '');

const migrations = readdirSync(join('supabase', 'migrations')).filter((f) => f.endsWith('.sql')).sort();
const allSql = migrations.map((f) => readFileSync(join('supabase', 'migrations', f), 'utf8')).join('\n');

out.push(
  '-- Esquema do banco do convite (Supabase / Postgres), gerado por `npm run db:schema`.',
  `-- Resultado das ${migrations.length} migrações de supabase/migrations/ (fonte de verdade). Só estrutura.`,
  '-- Nenhuma tabela é acessível a `anon`/`authenticated`: tudo passa pelas funções `bot_*`,',
  '-- executadas só pelas Edge Functions com `service_role`.',
  '',
  'set check_function_bodies = off;',
);

section('Extensões');
const extensions = [...new Set([...allSql.matchAll(/create extension if not exists\s+"?([\w-]+)"?/gi)].map((m) => m[1]))];
for (const name of extensions) out.push(`create extension if not exists "${name}" with schema extensions;`);

section('Funções');
const functions = await rows(`
  select p.oid, p.proname, pg_get_functiondef(p.oid) as def, pg_get_function_identity_arguments(p.oid) as args,
         has_function_privilege('service_role', p.oid, 'execute') as service,
         has_function_privilege('anon', p.oid, 'execute') as anon
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public'
     and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
   order by p.proname, args`);
for (const f of functions) out.push(`${f.def.trim()};`, '');

section('Tabelas');
const tables = await rows(`
  select c.oid, c.relname, c.relrowsecurity as rls, obj_description(c.oid, 'pg_class') as comment
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relkind = 'r' order by c.relname`);
const foreignKeys = [];
for (const t of tables) {
  const cols = await rows(`
    select a.attname, format_type(a.atttypid, a.atttypmod) as type, a.attnotnull, a.attidentity, a.attgenerated,
           pg_get_expr(d.adbin, d.adrelid) as def, col_description(a.attrelid, a.attnum) as comment
      from pg_attribute a left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
     where a.attrelid = ${t.oid} and a.attnum > 0 and not a.attisdropped order by a.attnum`);
  const cons = await rows(`
    select conname, contype, pg_get_constraintdef(oid) as def from pg_constraint
     where conrelid = ${t.oid} order by case contype when 'p' then 0 when 'u' then 1 when 'c' then 2 else 3 end, conname`);
  const lines = cols.map((c) => {
    let line = `  ${c.attname} ${c.type}`;
    if (c.attidentity === 'a') line += ' generated always as identity';
    else if (c.attidentity === 'd') line += ' generated by default as identity';
    else if (c.attgenerated === 's') line += ` generated always as (${c.def}) stored`;
    else if (c.def) line += ` default ${c.def}`;
    if (c.attnotnull && !c.attidentity) line += ' not null';
    return line;
  });
  for (const k of cons) {
    if (k.contype === 'f') foreignKeys.push(`alter table public.${t.relname} add constraint ${k.conname} ${k.def};`);
    else if (k.contype !== 'n') lines.push(`  constraint ${k.conname} ${k.def}`);
  }
  if (t.comment) out.push(`-- ${t.comment.replace(/\n/g, '\n-- ')}`);
  out.push(`create table public.${t.relname} (`, lines.join(',\n'), ');');
  for (const c of cols) if (c.comment) out.push(`comment on column public.${t.relname}.${c.attname} is '${c.comment.replace(/'/g, "''")}';`);
  out.push('');
}
out.push(...foreignKeys);

section('Índices');
for (const i of await rows(`
  select indexdef from pg_indexes i
   where schemaname = 'public'
     and not exists (select 1 from pg_constraint k where k.conname = i.indexname)
   order by tablename, indexname`)) out.push(`${i.indexdef};`);

section('Gatilhos');
for (const g of await rows(`
  select pg_get_triggerdef(t.oid) as def from pg_trigger t join pg_class c on c.oid = t.tgrelid
    join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and not t.tgisinternal order by c.relname, t.tgname`)) out.push(`${g.def};`);

section('Segurança: RLS e permissões');
out.push('-- RLS ligado em todas as tabelas, sem políticas: anon/authenticated não leem nem escrevem nada.');
for (const t of tables) if (t.rls) out.push(`alter table public.${t.relname} enable row level security;`);
out.push('', 'revoke all on all tables in schema public from anon, authenticated;');
for (const f of functions) {
  const sig = `public.${f.proname}(${f.args})`;
  out.push(`revoke all on function ${sig} from public, anon, authenticated;`);
  if (f.service) out.push(`grant execute on function ${sig} to service_role;`);
  if (f.anon) throw new Error(`${sig} está liberada para anon: revise a migração.`);
}

section('Agendamentos (pg_cron, só no Supabase)');
out.push('-- Horários em UTC: o relatório diário das 12h UTC chega às 9h de Brasília.');
const jobs = [...allSql.matchAll(/cron\.schedule\(\s*'([^']+)',\s*'([^']+)',\s*(\$(\w*)\$[\s\S]*?\$\4\$|'[^']*')/g)];
for (const [, name, schedule, command] of jobs) out.push(`select cron.schedule('${name}', '${schedule}', ${command.replace(/\s+/g, ' ')});`);

writeFileSync(join('supabase', 'schema.sql'), `${out.join('\n').replace(/\n{3,}/g, '\n\n').trim()}\n`);
await db.close();
console.log(`supabase/schema.sql: ${tables.length} tabelas, ${functions.length} funções, ${jobs.length} agendamentos.`);
